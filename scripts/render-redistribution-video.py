"""Render the parcel redistribution experiment from its recorded MuJoCo states.

Usage (from the site directory, with the native MuJoCo 3.8.1 dependencies):
  python scripts/render-redistribution-video.py recording.json.gz \
      --output assets/result/redistribution.mp4

Input is a JSON or gzipped JSON recording with sceneXml and frames containing
time, qpos, and optional qvel. Charts and force readouts use recorded telemetry.
The renderer holds the most recent sample and never integrates dynamics.
"""

from __future__ import annotations

import argparse
import bisect
import gzip
import hashlib
import importlib.util
import json
import math
from pathlib import Path
import subprocess
import sys


# Reuse the native scene renderer, palette, fonts, and MP4 validation already
# used by the autonomous acquisition recordings. Suppress generated bytecode.
sys.dont_write_bytecode = True
autonomous_spec = importlib.util.spec_from_file_location(
    "autonomous_video", Path(__file__).with_name("render-autonomous-video.py")
)
autonomous = importlib.util.module_from_spec(autonomous_spec)
autonomous_spec.loader.exec_module(autonomous)

from PIL import Image, ImageDraw


PALETTE = autonomous.PALETTE
INK, MUTED, BACKGROUND, BORDER = (
    autonomous.INK, autonomous.MUTED, autonomous.BACKGROUND, autonomous.BORDER
)
NAVY, TEAL, ORANGE = "#17394f", "#007d69", "#b45d18"
WIDTH, HEIGHT = 1280, 720


def first(mapping, *names):
    return autonomous.first(mapping, names)


def is_number(value):
    return type(value) in (int, float) and math.isfinite(value)


def number(value, digits=3, suffix=""):
    return f"{value:.{digits}f}{suffix}" if is_number(value) else "n/a"


def percent(value):
    return number(value * 100, 1, "%") if is_number(value) else "n/a"


def xy(position):
    if isinstance(position, dict):
        position = [position.get("x"), position.get("y")]
    if isinstance(position, (list, tuple)) and len(position) >= 2 and all(map(is_number, position[:2])):
        return tuple(position[:2])
    return None


def measured_metrics(frame):
    row = frame.get("row", {})
    obj = frame.get("object", {})
    contact = obj.get("contact", {})
    limit_keys = ("jointLimitExcess", "jointViolation", "maxJointViolation", "maximumJointViolation")
    limits = first(row, *limit_keys)
    if limits is None:
        limits = first(obj, *limit_keys)
    pad_forces = first(contact, "padForces", "normalForces", "normals")
    contacts = contact.get("pads")
    if pad_forces is None and isinstance(contacts, list):
        pad_forces = [
            sum(pad["force"] for pad in contacts if pad.get("side") == side and pad.get("sign") == sign and is_number(pad.get("force")))
            for side, sign in [("left", "plus"), ("left", "minus"), ("right", "plus"), ("right", "minus")]
        ]
    return {
        "imbalance": first(row, "imbalance", "loadImbalance", "loadCV", "sectorCV"),
        "distortion": first(row, "distortion", "sectorDistortion", "areaRatio", "widthRatio"),
        "transferred": first(row, "transferredLoad", "relocatedDemand", "movedLoad", "movedDemand"),
        "normal": first(row, "normalForce", "normalForceN", "padForce", "padNormalForce"),
        "slip": first(row, "slipSpeed", "slipMps", "maxSlipSpeed", "maxSlip"),
        "limits": limits,
        "pad_forces": pad_forces,
        "support_force": contact.get("supportForce"),
        "cone_use": contact.get("utilization"),
    }


def paste_view(image, draw, pixels, box, heading):
    x, y, width, height = box
    view = Image.fromarray(pixels).resize((width, height))
    image.paste(view, (x, y))
    draw.rectangle((x, y, x + width, y + 25), fill=NAVY)
    draw.text((x + 10, y + 4), heading, font=autonomous.font(13, True), fill="white")


def short_text(draw, position, value, size, color, width, bold=False):
    font = autonomous.font(size, bold)
    value = str(value)
    if draw.textlength(value, font=font) > width:
        while value and draw.textlength(value + "…", font=font) > width:
            value = value[:-1]
        value += "…"
    draw.text(position, value, font=font, fill=color)


def pad_layout(recording):
    raw = recording.get("pads") or recording.get("layout", {}).get("pads") or []
    pads = []
    for index, pad in enumerate(raw):
        if isinstance(pad, dict):
            position = xy(first(pad, "pos", "position", "center") or pad)
            label = first(pad, "id", "name", "label") or index + 1
            half_size = xy(first(pad, "halfSize", "halfExtents"))
        else:
            position = xy(pad)
            label = index + 1
            half_size = None
        if position:
            pads.append((str(label), position, half_size))
    return pads


def plot_handling_map(draw, pads, hotspot, hotspot_radius, trace, current, chosen):
    if not pads or current is None:
        return
    endpoints = []
    for _, (x, y), half_size in pads:
        half_x, half_y = half_size or (0, 0)
        endpoints.extend([(x - half_x, y - half_y), (x + half_x, y + half_y)])
    if hotspot:
        x, y = hotspot
        radius = hotspot_radius if is_number(hotspot_radius) else 0
        endpoints.extend([(x - radius, y - radius), (x + radius, y + radius)])
    x_values, y_values = zip(*endpoints)
    min_x, max_x, min_y, max_y = min(x_values), max(x_values), min(y_values), max(y_values)
    left, top, right, bottom = 532, 81, 768, 282
    center = ((min_x + max_x) / 2, (min_y + max_y) / 2)
    scale = min((right - left - 66) / max(.4, max_x - min_x), (bottom - top - 63) / max(.4, max_y - min_y))

    def project(position):
        return ((left + right) / 2 + scale * (position[0] - center[0]),
                (top + bottom) / 2 + 4 - scale * (position[1] - center[1]))

    def visible(point):
        x, y = point
        return left + 7 < x < right - 7 and top + 30 < y < bottom - 23

    draw.rounded_rectangle((left, top, right, bottom), radius=7, fill="white", outline=BORDER)
    draw.text((left + 9, top + 6), "LOCAL HANDLING MAP (m)", font=autonomous.font(11, True), fill=NAVY)
    route = [project(position) for position in trace]
    for a, b in zip(route, route[1:]):
        if visible(a) and visible(b):
            draw.line([a, b], fill="#c18440", width=2)
    for label, position, half_size in pads:
        x, y = project(position)
        half_x, half_y = (max(3, scale * value) for value in half_size) if half_size else (6, 6)
        fill = "#d3f0e7" if label == chosen else "#dbe7ee"
        draw.rectangle((x - half_x, y - half_y, x + half_x, y + half_y), fill=fill, outline=TEAL if label == chosen else NAVY)
        label_width = draw.textlength(label, font=autonomous.font(10))
        label_x = x + half_x + 3
        if label_x + label_width > right - 6:
            label_x = max(left + 6, x - half_x - label_width - 3)
        short_text(draw, (label_x, y - 7), label, 10, INK, right - label_x - 6)
    if hotspot:
        x, y = project(hotspot)
        radius = max(4, scale * hotspot_radius) if is_number(hotspot_radius) else 9
        draw.ellipse((x - radius, y - radius, x + radius, y + radius), outline="#be7044", width=2)
    x, y = project(current)
    if visible((x, y)):
        draw.ellipse((x - 5, y - 5, x + 5, y + 5), fill=ORANGE, outline="white")
    draw.text((left + 9, bottom - 17), "Box: support  /  Ring: hotspot  /  Dot: parcel", font=autonomous.font(10), fill=MUTED)


def plot_sector_angles(draw, frame, hotspot):
    left, top, right, bottom = 532, 292, 768, 540
    draw.rounded_rectangle((left, top, right, bottom), radius=7, fill="white", outline=BORDER)
    draw.text((left + 9, top + 6), "CYCLIC REFERENCE BOUNDARIES", font=autonomous.font(11, True), fill=NAVY)
    row = frame.get("row", {})
    angles = row.get("angles")
    if not isinstance(angles, list) or len(angles) < 2 or not all(map(is_number, angles)):
        draw.text((left + 9, top + 26), "No recorded sector angles", font=autonomous.font(11), fill=MUTED)
        return

    center = (650, 412)
    radius = 82

    def project(theta, r=radius):
        return (center[0] + r * math.cos(theta), center[1] - r * math.sin(theta))

    widths = [(b - a) % math.tau for a, b in zip(angles, [*angles[1:], angles[0]])]
    narrow = min(range(len(widths)), key=widths.__getitem__)
    draw.ellipse((center[0] - radius, center[1] - radius, center[0] + radius, center[1] + radius), fill="#f3f7fb", outline=BORDER)
    wedge = [project(angles[narrow] + widths[narrow] * index / 16) for index in range(17)]
    draw.polygon([center, *wedge], fill="#f2c5a9")
    for theta in angles:
        draw.line([center, project(theta)], fill=NAVY, width=1)
    for point, color, distance in [(hotspot, ORANGE, radius + 6), (xy(frame.get("object", {}).get("pos")), TEAL, radius - 10)]:
        if point is None:
            continue
        x, y = project(math.atan2(point[1], point[0]), distance)
        draw.ellipse((x - 4, y - 4, x + 4, y + 4), fill=color, outline="white")
    draw.text((left + 9, bottom - 34), f"Smallest sector: {math.degrees(widths[narrow]):.2f} degrees", font=autonomous.font(11, True), fill=INK)
    draw.text((left + 9, bottom - 17), "Orange: source  /  Green: parcel bearing", font=autonomous.font(10), fill=MUTED)


def render_frame(scene, frame, histories):
    owner = autonomous.carrier_id(frame)
    obj = frame.get("object", {})
    position = xy(first(obj, "pos", "p", "tray"))
    if owner in scene.base and position:
        x, y, _ = scene.base[owner]
        q = frame["qpos"]
        if len(q) == scene.model.nq and math.dist((q[x], q[y]), position) > 1.7:
            # The parcel stays centered during a long approach. This copy only
            # changes camera selection and does not change the displayed data.
            camera_object = {name: obj.get(name) for name in ("pos", "p", "tray")}
            frame = {**frame, "workflow": {}, "object": camera_object}
    return scene.render(frame, histories)


def compose(world, closeup, recording, frame, metrics, history, plot_config, map_config, trace, replay_time, title):
    image = Image.new("RGB", (WIDTH, HEIGHT), BACKGROUND)
    draw = ImageDraw.Draw(image)
    draw.rectangle((0, 0, WIDTH, 70), fill=NAVY)
    short_text(draw, (18, 9), title, 25, "white", 1244, True)
    draw.text((19, 43), "Recorded MuJoCo state playback   /   Native contact telemetry   /   Zero-order hold", font=autonomous.font(13), fill="#ccdee9")

    # The existing renderer centers the circular arena in a wide frame.
    # Crop the side margins to leave room for the two measured plan views.
    paste_view(image, draw, world[:, 122:630], (16, 81, 508, 459), "FLEET OVERVIEW / MEASURED BASE TRAJECTORIES")
    paste_view(image, draw, closeup, (788, 81, 476, 334), "PHYSICAL PARCEL AND GRIPPER CONTACTS")

    config = recording.get("config", {})
    workflow = frame.get("workflow", {})
    row = frame.get("row", {})
    obj = frame.get("object", {})
    owner = autonomous.carrier_id(frame)
    n = first(row, "N", "N_active", "nActive") or config.get("N")
    k = row.get("k", config.get("k"))
    d = math.gcd(int(n), int(k)) if is_number(n) and is_number(k) else "n/a"
    stage = first(workflow, "stage", "phase") or obj.get("phase", "Unlabelled phase")
    selected = first(workflow, "padId", "safePadId", "supportId", "selectedPad")
    support = first(obj, "supportId", "padId", "supportPad")
    if isinstance(selected, dict):
        selected = first(selected, "id", "name", "label")
    if isinstance(support, dict):
        support = first(support, "id", "name", "label")
    pads, hotspot, radius = map_config
    plot_handling_map(draw, pads, hotspot, radius, trace, xy(first(obj, "pos", "p", "tray")), str(selected))
    plot_sector_angles(draw, frame, hotspot)
    ids = [robot.get("id") for robot in frame.get("robots", frame.get("agents", [])) if isinstance(robot, dict)]
    ids = [robot for robot in ids if isinstance(robot, int) and robot > 0]
    if ids:
        draw.rectangle((16, 516, 524, 540), fill=BACKGROUND)
        for index, robot in enumerate(ids[:9]):
            x = 27 + index * 53
            color = PALETTE[(robot - 1) % len(PALETTE)]
            draw.rectangle((x, 524, x + 10, 534), fill=color)
            draw.text((x + 15, 520), f"ID {robot}" + (" *" if robot == owner else ""), font=autonomous.font(11, True), fill=color)

    draw.rounded_rectangle((788, 425, 1264, 704), radius=9, fill="white", outline=BORDER)
    draw.text((801, 434), f"Playback {replay_time:.2f} s   |   Recorded state {frame['time']:.2f} s", font=autonomous.font(13, True), fill=MUTED)
    short_text(draw, (800, 456), str(stage).replace("_", " ").replace("-", " ").capitalize(), 21, NAVY, 448, True)
    readings = [
        f"Carrier {owner if owner is not None else 'unassigned'}   |   N={n or 'n/a'}, k={k or 'n/a'}, gcd={d}",
        f"Selected support {selected if selected is not None else 'n/a'}   |   Actual support {support if support is not None else 'n/a'}",
        f"Summed pad normals {number(metrics['normal'], 2, ' N')}   |   Max slip speed {number(metrics['slip'], 4, ' m/s')}",
        f"Relative load RMS {percent(metrics['imbalance'])}   |   Min sector angle {percent(metrics['distortion'])} of uniform",
        f"Certified relocated share {percent(metrics['transferred'])}   |   Joint excess {number(metrics['limits'], 5)}",
    ]
    pad_forces = metrics["pad_forces"]
    if isinstance(pad_forces, list) and len(pad_forces) == 4 and all(map(is_number, pad_forces)):
        readings.append("Pad normals (N)   " + "   /   ".join(f"{label} {number(value, 1)}" for label, value in zip(("L+", "L-", "R+", "R-"), pad_forces)))
    if is_number(metrics["support_force"]) or is_number(metrics["cone_use"]):
        readings.append(f"Upward support {number(metrics['support_force'], 2, ' N')}   |   Friction cone use {percent(metrics['cone_use'])}")
    for index, line in enumerate(readings):
        short_text(draw, (801, 492 + index * 20), line, 13, INK, 451)

    events = recording.get("events", [])
    event_times = [event.get("time", math.inf) for event in events]
    event_index = bisect.bisect_right(event_times, frame["time"] + 1e-9) - 1
    if event_index >= 0:
        draw.text((801, 629), "LATEST RECORDED EVENT", font=autonomous.font(11, True), fill=MUTED)
        event = events[event_index]
        label = first(event, "message", "type", "event") or "Event"
        short_text(draw, (801, 650), f"{event['time']:.2f} s   {label}", 13, INK, 451, True)

    start = recording["frames"][0]["time"]
    duration = recording["frames"][-1]["time"] - start
    for index, (name, label, units, color, ylim) in enumerate(plot_config):
        points = [(f["time"] - start, values[name] * 100 if is_number(values[name]) else None) for f, values in history]
        autonomous.chart(draw, (16 + index * 382, 553, 369, 151), points, label, units, color, duration, ylim)
    return image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--title", default="Contact-only parcel redistribution and support takeover")
    parser.add_argument("--fps", type=int, default=10)
    parser.add_argument("--max-seconds", type=float)
    parser.add_argument("--poster-time", type=float, help="Recorded time for the poster image, in seconds")
    args = parser.parse_args()
    if not 1 <= args.fps <= 60 or (args.max_seconds is not None and args.max_seconds <= 0):
        raise ValueError("Use 1 to 60 fps and a positive excerpt duration")

    source = args.input.read_bytes()
    if source.startswith(b"\x1f\x8b"):
        source = gzip.decompress(source)
    recording = json.loads(source)
    frames = recording.get("frames", [])
    if not frames:
        raise ValueError("Recording has no physical-state frames")
    times = [float(frame["time"]) for frame in frames]
    if not all(map(math.isfinite, times)) or times != sorted(times):
        raise ValueError("Physical-state timestamps must be finite and ordered")
    recording["events"] = sorted(recording.get("events", []), key=lambda event: event.get("time", math.inf))
    metrics = list(map(measured_metrics, frames))
    plot_config = []
    for name, label, color in [
        ("imbalance", "Fixed-angle order-k load RMS", TEAL),
        ("distortion", "Min sector angle / uniform angle", "#7450a0"),
    ]:
        values = [100 * row[name] for row in metrics if is_number(row[name])]
        plot_config.append((name, label, "%", color, (0, max(100, max(values) * 1.06)) if values else (0, 100)))
    hotspot = recording.get("hotspot") or recording.get("hotSpot") or recording.get("layout", {}).get("hotspot") or {}
    center = first(hotspot, "center", "pos", "position") if isinstance(hotspot, dict) else hotspot
    radius = hotspot.get("radius") if isinstance(hotspot, dict) else None
    map_config = (pad_layout(recording), xy(center), radius)

    final = min(times[-1], times[0] + args.max_seconds) if args.max_seconds else times[-1]
    count = int(round((final - times[0]) * args.fps)) + 1
    poster_index = count // 2
    if args.poster_time is not None:
        poster_index = max(0, min(count - 1, round((args.poster_time - times[0]) * args.fps)))
    ffmpeg = autonomous.ffmpeg_path()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    maxrate = max(350, min(1600, int(21 * 1024 * 1024 * 8 / (1000 * count / args.fps))))
    command = [ffmpeg, "-y", "-hide_banner", "-loglevel", "warning", "-f", "rawvideo",
               "-pix_fmt", "rgb24", "-s", f"{WIDTH}x{HEIGHT}", "-r", str(args.fps),
               "-i", "pipe:0", "-an", "-c:v", "libx264", "-preset", "fast", "-crf", "25",
               "-maxrate", f"{maxrate}k", "-bufsize", f"{2 * maxrate}k", "-pix_fmt", "yuv420p",
               "-movflags", "+faststart", str(args.output)]
    process = subprocess.Popen(command, stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
    scene = None
    scene_hashes = []
    robot_histories = {}
    trace = []
    history = []
    last_sample = -1
    poster_source_time = None
    try:
        for index in range(count):
            time = min(final, times[0] + index / args.fps)
            sample = max(0, bisect.bisect_right(times, time + 1e-9) - 1)
            frame = frames[sample]
            xml = autonomous.scene_xml(recording, frame)
            digest = hashlib.sha256(xml.encode()).hexdigest() if xml else None
            if scene is None or scene.digest != digest:
                if scene:
                    scene.close()
                scene = autonomous.NativeScene(xml)
                scene_hashes.append(scene.digest)
            for cursor in range(last_sample + 1, sample + 1):
                logged = frames[cursor]
                history.append((logged, metrics[cursor]))
                position = xy(first(logged.get("object", {}), "pos", "p", "tray"))
                if position:
                    trace.append(position)
                q = logged["qpos"]
                if len(q) == scene.model.nq:
                    for robot, (x, y, _) in scene.base.items():
                        robot_histories.setdefault(robot, []).append([q[x], q[y], .025])
            last_sample = sample
            world, closeup = render_frame(scene, frame, robot_histories)
            image = compose(world, closeup, recording, frame, metrics[sample], history, plot_config, map_config, trace, time, args.title)
            process.stdin.write(image.tobytes())
            if index in (0, count // 2, count - 1):
                image.save(args.output.with_name(f"{args.output.stem}-frame-{index:05d}.png"))
            if index == poster_index:
                image.save(args.output.with_name(f"{args.output.stem}-poster.png"))
                poster_source_time = frame["time"]
            if index % 100 == 0:
                print(json.dumps({"rendered": index, "total": count, "sourceTime": frame["time"]}), flush=True)
        process.stdin.close()
        errors = process.stderr.read().decode(errors="replace")
        if process.wait():
            raise RuntimeError(f"FFmpeg encode failed: {errors}")
    except Exception:
        process.kill()
        process.wait()
        raise
    finally:
        if scene:
            scene.close()

    validation = autonomous.validate_mp4(ffmpeg, args.output, count, args.fps)
    report = {
        "status": "passed", "input": str(args.input.resolve()), "output": str(args.output.resolve()),
        "inputSha256": hashlib.sha256(source).hexdigest(),
        "outputSha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
        "bytes": args.output.stat().st_size, "width": WIDTH, "height": HEIGHT,
        "fps": args.fps, "frames": count, "mujoco": autonomous.mujoco.__version__,
        "sourceFirstTime": times[0], "sourceLastTime": times[-1], "renderedLastTime": final,
        "posterSourceTime": poster_source_time,
        "truncated": final < times[-1], "sceneSha256": list(dict.fromkeys(scene_hashes)),
        "statePolicy": "Forward kinematics of logged qpos, zero-order hold, no dynamics rollout",
        "telemetryPolicy": "Recorded data only; absent measurements remain unavailable",
        "validation": validation, "browserVerification": False, "hardwareVerification": False,
    }
    args.output.with_suffix(".video.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print(json.dumps(report), flush=True)


if __name__ == "__main__":
    main()
